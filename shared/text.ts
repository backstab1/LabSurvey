// Текст вопросов и вариантов без разметки — для выгрузок, таблиц, списков в админке

/** Картинки убираются, ссылки и выделение — только текст, подстановки {{Q1}} — как [Q1], пробелы схлопываются */
export function plainText(text: string | undefined): string {
  if (!text) return '';
  return text
    .replace(/\{\{\s*([\w.]+)\s*\}\}/g, '[$1]')
    .replace(/!\[[^\]]*\]\([^)]*\)/g, '')
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
    .replace(/\*\*([^*]+)\*\*/g, '$1')
    .replace(/(^|[^*])\*([^*]+)\*/g, '$1$2')
    .replace(/\s+/g, ' ')
    .trim();
}
